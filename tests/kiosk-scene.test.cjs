// 店内画の試作：状況が変わった途中で手を止める。在庫を二重に取らず、元データを書き換えない。
const assert = require('node:assert/strict');
require('../js/kiosk-scene-core.js');
const config = require('../data/kiosk-scene.json');
const Scene = globalThis.KioskScene;
function until(scene, predicate, limit = 120) {
  for (let i = 0; i < limit * 60; i++) {
    if (predicate(scene)) return;
    scene.step(1/60);
  }
  assert.fail('到達しなかった状態: '+scene.phase+' / '+scene.reason);
}
const snapshot = {v:1,day:4,t:450,stock:{cf_black:2,dr_sports:1}};
const before = JSON.stringify({config,snapshot});
const scene = new Scene(config,snapshot);
until(scene,s=>s.phase==='reach'&&s.reach>.5);
scene.setStock(0,0);
scene.step(1/60);
assert.equal(scene.phase,'retract','手を伸ばす途中の品切れで中断');
assert.equal(scene.held,null,'品切れの商品を持たない');
const extended = scene.reach;
scene.step(.2);
assert.ok(scene.reach < extended,'腕を戻す');
until(scene,s=>s.held!==null);
assert.equal(scene.held,1,'代わりのスポーツドリンクを取る');
assert.deepEqual(scene.stock,[0,0],'代わりを1本だけ減らす');
until(scene,s=>s.phase==='done');
assert.deepEqual([scene.x,scene.y],config.exit.at(-1),'会計して出口へ');
assert.deepEqual(scene.unpaid,[0,0]);
assert.deepEqual(scene.purchased,[0,1]);
assert.equal(scene.paymentCount,1,'会計は1回だけ');
scene.step(1);
assert.deepEqual(scene.stock,[0,0],'取り終えた品を再び引かない');
assert.equal(JSON.stringify({config,snapshot}),before,'設定と元の棚在庫を変更しない');
scene.reset();
assert.deepEqual(scene.stock,[2,1],'初めの在庫に戻る');
assert.equal(scene.held,null);
assert.deepEqual(scene.purchased,[0,0],'再生し直したら会計記録も戻る');
assert.equal(scene.paymentCount,0);
until(scene,s=>s.held===0);
scene.setStock(0,0);
scene.step(.2);
assert.equal(scene.held,0,'取り終えた飲み物は後の品切れで消えない');
const empty = new Scene(config,{stock:{cf_black:0,dr_sports:0}});
until(empty,s=>s.phase==='done');
assert.equal(empty.held,null);
assert.equal(empty.paymentCount,0,'買わずに帰る人は会計しない');
assert.deepEqual(empty.stock,[0,0]);
assert.deepEqual([empty.x,empty.y],config.exit.at(-1),'両方品切れなら入口へ逆走せず出口へ');
for(const fps of [15,30,60]){
  const run = new Scene(config,snapshot);
  for(let i=0;i<90*fps;i++)run.step(1/fps);
  assert.equal(run.phase,'done');
  assert.equal(run.held,0);
  assert.deepEqual(run.stock,[1,1],'FPSが違っても同じ結果');
  assert.deepEqual(run.unpaid,[0,0]);
  assert.deepEqual(run.purchased,[1,0]);
  assert.equal(run.paymentCount,1);
}
const waiting = new Scene(config,snapshot);
waiting.setRegisterBusy(true);
until(waiting,s=>s.phase==='queue');
const waitingPoint=[waiting.x,waiting.y];
for(let i=0;i<15;i++)waiting.step(1);
assert.equal(waiting.phase,'queue','対応中は時間が過ぎても待ち続ける');
assert.deepEqual([waiting.x,waiting.y],waitingPoint,'待つ間に足元がずれない');
assert.deepEqual(waiting.unpaid,[1,0],'会計前の品は手元に残る');
assert.deepEqual(waiting.purchased,[0,0]);
waiting.setStock(0,0);
waiting.setRegisterBusy(false);
until(waiting,s=>s.phase==='pay');
assert.deepEqual([waiting.x,waiting.y],config.register.approach.at(-1));
assert.equal(waiting.setRegisterBusy(true),false,'自分の会計中は割り込まれない');
until(waiting,s=>s.paymentCount===1);
assert.equal(waiting.held,0,'支払い後も飲み物を持つ');
assert.deepEqual(waiting.stock,[0,1],'会計時に棚からもう一度引かない');
assert.deepEqual(waiting.unpaid,[0,0]);
assert.deepEqual(waiting.purchased,[1,0]);
until(waiting,s=>s.phase==='pack');
assert.deepEqual([waiting.x,waiting.y],config.register.pack.at(-1),'レジの横によける');
until(waiting,s=>s.phase==='done');
for(let i=0;i<10;i++)waiting.step(1);
assert.equal(waiting.paymentCount,1);
assert.deepEqual(waiting.purchased,[1,0]);
waiting.reset();
assert.equal(waiting.registerBusy,false);
const invalid = new Scene(config,{stock:{cf_black:-2,dr_sports:NaN}});
assert.deepEqual(invalid.stock,[3,3]);
invalid.setStock(0,Infinity);invalid.setStock(-1,3);
assert.deepEqual(invalid.stock,[3,3]);
console.log('kiosk-scene ok: 品切れ・選び直し・棚/未会計/会計済み・待機/再開・一度だけの会計・退出・FPS');
